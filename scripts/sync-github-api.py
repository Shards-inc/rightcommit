#!/usr/bin/env python3
"""Bundle the official GitHub REST endpoint catalog; no runtime download needed."""
import argparse
import hashlib
import json
from pathlib import Path
from urllib.request import urlopen

SOURCE = 'https://raw.githubusercontent.com/github/rest-api-description/main/descriptions/api.github.com/api.github.com.json'
ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--schema', type=Path, help='Use a downloaded official OpenAPI schema')
args = parser.parse_args()
raw = args.schema.read_bytes() if args.schema else urlopen(SOURCE, timeout=60).read()
schema = json.loads(raw)
operations = []
for path, methods in schema['paths'].items():
    for method, operation in methods.items():
        if method not in ('get', 'post', 'put', 'patch', 'delete', 'head', 'options'):
            continue
        server = (operation.get('servers') or methods.get('servers') or [{}])[0].get('url', '')
        if server and server != 'https://uploads.github.com':
            raise ValueError(f'Unexpected GitHub API server: {server}')
        operations.append(dict(id=operation['operationId'], method=method.upper(), path=path,
                               label=operation.get('summary', operation['operationId']),
                               url=operation.get('externalDocs', {}).get('url', ''), server=server))
assert len({op['id'] for op in operations}) == len(operations)
header = f'// Generated by scripts/sync-github-api.py from {SOURCE}\n// Source file sha256 {hashlib.sha256(raw).hexdigest()}; MIT license: licenses/github-rest-api-description.md\n'
(ROOT / 'web/github-api.js').write_text(header + 'window.githubApiCatalog=' + json.dumps(sorted(operations, key=lambda op: op['id']), separators=(',', ':')) + ';\n')
print(f'Bundled {len(operations)} GitHub REST operations')
